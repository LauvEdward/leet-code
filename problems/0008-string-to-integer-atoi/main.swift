func check(_ s: String, _ want: Int, line: UInt = #line) {
    let got = Solution().myAtoi(s)
    precondition(got == want, "line \(line): got \(got), want \(want)")
}

check("42", 42)
check("   -042", -42)
check("1337c0d3", 1337)
check("0-1", 0)
check("words and 987", 0)
check("", 0)
